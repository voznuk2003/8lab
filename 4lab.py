import numpy as np
import matplotlib.pyplot as plt

# БЛОК 1: ИНИЦИАЛИЗАЦИЯ ПАРАМЕТРОВ ШУМА И СИГНАЛА
# Здесь задаются основные параметры для генерации случайного шума и построения графиков
mean = 9                    # Математическое ожидание для нормального распределения шума
sigma = 11                  # Среднеквадратическое отклонение (стандартное отклонение) для нормального распределения
N = 1024                    # Количество отсчетов (длина массива) для всех сигналов

# БЛОК 2: ЗАДАНИЕ ГРАНИЦ ВРЕМЕННОЙ ОСИ
# Определение диапазона по оси X для построения гармонических сигналов
min_limit_x = 0            # Нижний предел временной оси (начальное время)
max_limit_x = 10*np.pi     # Верхний предел временной оси (10π радиан)

# БЛОК 3: ГЕНЕРАЦИЯ ШУМОВОГО СИГНАЛА
# Создание массива случайных чисел, распределенных по нормальному закону
massive_normal = np.random.normal(mean, sigma, N)

# БЛОК 4: ВЫЧИСЛЕНИЕ И ВИЗУАЛИЗАЦИЯ ПРЕОБРАЗОВАНИЯ ФУРЬЕ ДЛЯ ШУМА
# Прямое быстрое преобразование Фурье (БПФ) шумового сигнала и взятие модуля
l = abs(np.fft.fft(massive_normal))
plt.figure(1)                     # Создание нового графического окна с номером 1
plt.plot(l)                       # Построение графика амплитудного спектра шума
plt.title('График преобразования Фурье для шума')  # Заголовок графика
plt.grid('on')                    # Включение отображения сетки на графике

# БЛОК 5: ВИЗУАЛИЗАЦИЯ ШУМОВОГО СИГНАЛА ВО ВРЕМЕННОЙ ОБЛАСТИ
plt.figure(2)                     # Создание нового графического окна с номером 2
plt.plot(massive_normal)          # Построение графика шумового сигнала во временной области
plt.title('График шума')          # Заголовок графика
plt.grid('on')                    # Включение сетки

# БЛОК 6: ГЕНЕРАЦИЯ ПЕРВОЙ СИНУСОИДАЛЬНОЙ СОСТАВЛЯЮЩЕЙ
# Создание первой гармонической составляющей с заданными параметрами
ampl1 = 1                         # Амплитуда первой синусоиды
f1 = 1                            # Частота первой синусоиды (в радианах/сек)
x1 = np.linspace(min_limit_x, max_limit_x, N)  # Создание временной оси
y1 = ampl1*np.sin(f1*x1)          # Вычисление значений первой синусоиды
plt.figure(3)                     # Создание нового графического окна
plt.plot(y1)                       # Построение графика первой синусоиды
plt.title('1 синусоида')          # Заголовок
plt.grid('on')                    # Включение сетки

# БЛОК 7: ГЕНЕРАЦИЯ ВТОРОЙ СИНУСОИДАЛЬНОЙ СОСТАВЛЯЮЩЕЙ
# Аналогично создается вторая гармоническая составляющая
ampl2 = 1                         # Амплитуда второй синусоиды
f2 = 5                            # Частота второй синусоиды
x2 = np.linspace(min_limit_x, max_limit_x, N)  # Временная ось (может быть переиспользована x1)
y2 = ampl2*np.sin(f2*x2)          # Вычисление значений второй синусоиды
plt.figure(4)                     # Новое графическое окно
plt.plot(y2)                       # График второй синусоиды
plt.title('2 синусоида')          # Заголовок
plt.grid('on')                    # Сетка

# БЛОК 8: ГЕНЕРАЦИЯ ТРЕТЬЕЙ СИНУСОИДАЛЬНОЙ СОСТАВЛЯЮЩЕЙ
# Создание третьей гармонической составляющей
ampl3 = 1                         # Амплитуда третьей синусоиды
f3 = 6                            # Частота третьей синусоиды
x3 = np.linspace(min_limit_x, max_limit_x, N)  # Временная ось
y3 = ampl3*np.sin(f3*x3)          # Вычисление значений третьей синусоиды
plt.figure(5)                     # Новое графическое окно
plt.plot(y3)                       # График третьей синусоиды
plt.title('3 синусоида')          # Заголовок
plt.grid('on')                    # Сетка

# БЛОК 9: ГЕНЕРАЦИЯ ЧЕТВЕРТОЙ СИНУСОИДАЛЬНОЙ СОСТАВЛЯЮЩЕЙ
# Создание четвертой гармонической составляющей (с наибольшей амплитудой)
ampl4 = 9                         # Амплитуда четвертой синусоиды (самая большая)
f4 = 4                            # Частота четвертой синусоиды
x4 = np.linspace(min_limit_x, max_limit_x, N)  # Временная ось
y4 = ampl4*np.sin(f4*x4)          # Вычисление значений четвертой синусоиды
plt.figure(6)                     # Новое графическое окно
plt.plot(y4)                       # График четвертой синусоиды
plt.title('4 синусоида')          # Заголовок
plt.grid('on')                    # Сетка

# БЛОК 10: ГЕНЕРАЦИЯ ПЯТОЙ СИНУСОИДАЛЬНОЙ СОСТАВЛЯЮЩЕЙ
# Создание пятой гармонической составляющей (возможна ошибка в amplitude2)
ampl5 = 6                         # Амплитуда пятой синусоиды (объявлена как 6)
f5 = 2                            # Частота пятой синусоиды
x5 = np.linspace(min_limit_x, max_limit_x, N)  # Временная ось
y5 = ampl2*np.sin(f5*x5)          # ВНИМАНИЕ: здесь используется ampl2 вместо ampl5! Возможная ошибка.
plt.figure(7)                     # Новое графическое окно
plt.plot(y5)                       # График пятой синусоиды
plt.title('5 синусоида')          # Заголовок
plt.grid('on')                    # Сетка

# БЛОК 11: ФОРМИРОВАНИЕ ЧИСТОГО СИГНАЛА (БЕЗ ШУМА)
# Суммирование всех пяти гармонических составляющих
z1 = y1 + y2 + y3 + y4 + y5       # Аддитивная сумма синусоид
plt.figure(8)                     # Новое графическое окно
plt.plot(z1)                       # График суммы синусоид
plt.title('Сумма сигналов (без шума)')  # Заголовок
plt.grid('on')                    # Сетка

# БЛОК 12: ФОРМИРОВАНИЕ АДДИТИВНОЙ СМЕСИ (СИГНАЛ + ШУМ)
# Добавление шума к чистому сигналу для получения реального сигнала с помехами
z2 = y1 + y2 + y3 + y4 + y5 + massive_normal  # Чистый сигнал + шум
plt.figure(9)                     # Новое графическое окно
plt.plot(z2)                       # График аддитивной смеси
plt.title('Сумма сигналов (с шумом)')  # Заголовок
plt.grid('on')                    # Сетка

# БЛОК 13: СПЕКТРАЛЬНЫЙ АНАЛИЗ АДДИТИВНОЙ СМЕСИ
# Выполнение прямого преобразования Фурье для анализа в частотной области
q1 = np.fft.fft(z2)               # Прямое БПФ (комплексный спектр)

# БЛОК 14: ВЫЧИСЛЕНИЕ АМПЛИТУДНОГО СПЕКТРА
# Получение амплитудного спектра путем взятия модуля комплексного спектра
q_1 = abs(q1)                     # Модуль комплексных чисел = амплитудный спектр
plt.figure(10)                    # Новое графическое окно
plt.plot(q_1)                      # График амплитудного спектра
plt.title('Амплитудный спектр аддитивной смеси сигналов и шума')  # Заголовок
plt.grid('on')                    # Сетка

# БЛОК 15: ВЫПОЛНЕНИЕ ОБРАТНОГО ПРЕОБРАЗОВАНИЯ ФУРЬЕ
# Восстановление сигнала из его спектра для проверки корректности преобразования
e1 = np.fft.ifft(q1)              # Обратное БПФ (должно восстановить исходный сигнал)
plt.figure(11)                    # Новое графическое окно
plt.title('ОПФ для аддитивной смеси сигналов и шума')  # Заголовок
plt.plot(e1)                       # График восстановленного сигнала
plt.grid('on')                    # Сетка

# БЛОК 16: АНАЛИЗ ПОГРЕШНОСТИ ВОССТАНОВЛЕНИЯ
# Вычисление разности между исходным и восстановленным сигналами
g1 = e1 - z2                      # Разность (должна быть близка к нулю при идеальном преобразовании)
plt.figure(12)                    # Новое графическое окно
plt.plot(g1)                       # График погрешности восстановления
plt.title('Разность ОПФ и аддитивной смеси сигналов и шума без преобразования \n')  # Заголовок
plt.grid('on')                    # Сетка

# БЛОК 17: ОТОБРАЖЕНИЕ ВСЕХ ПОСТРОЕННЫХ ГРАФИКОВ
plt.show()                        # Команда для отображения всех созданных графических окон

# БЛОК 18: ПРИМЕНЕНИЕ FFTSHIFT ДЛЯ ЦЕНТРИРОВАНИЯ СПЕКТРА
# Операция сдвига нулевой частоты в центр спектра для удобства визуализации
q_shifted = np.fft.fftshift(q_1)  # Сдвиг частот: отрицательные слева, положительные справа от центра
plt.figure(13)                    # Новое графическое окно
plt.plot(q_shifted)                # График амплитудного спектра после fftshift
plt.title('Амплитудный спектр после команды "fftshift"')  # Заголовок
plt.grid('on')                    # Сетка